import json
import shutil
from pathlib import Path

import pytest
from typer.testing import CliRunner

from velocia.cli.app import app
from velocia.config.models import DataFormat, Suite, WorkloadKind
from velocia.datagen.manifest import results_label
from velocia.datagen.tera import generate_tera, tera_dataset_id
from velocia.workloads import get_workload


def test_tera_workload_and_labels() -> None:
    tera = get_workload(Suite.tera)
    assert tera is not None and tera.kind is WorkloadKind.job
    assert [(u.id, u.job, u.sql) for u in tera.units()] == [("terasort", "terasort", None)]
    assert tera_dataset_id(1000, DataFormat.parquet_zstd) == "tera-rows1000-parquet-zstd"
    assert results_label("derived from TPC-H") == (
        "Data derived from TPC-H; not an official TPC result."
    )
    assert results_label("TeraSort-style data generated by Velocia") == (
        "Data: TeraSort-style data generated by Velocia."
    )


def test_cli_tera_options(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.chdir(tmp_path)
    cli = CliRunner()
    missing = cli.invoke(app, ["datagen", "--suite", "tera"])
    assert missing.exit_code == 1 and "--rows is required" in missing.output
    both = cli.invoke(app, ["datagen", "--suite", "tera", "--rows", "5", "--sf", "1"])
    assert both.exit_code == 1 and "--sf does not apply" in both.output


@pytest.mark.docker
@pytest.mark.skipif(shutil.which("docker") is None, reason="docker not available")
def test_teragen_is_deterministic_and_terasort_validates(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    drivers = tmp_path / "drivers"
    a, _ = generate_tera(50_000, DataFormat.parquet_zstd, tmp_path / "a", drivers, cores=2)
    b, _ = generate_tera(50_000, DataFormat.parquet_zstd, tmp_path / "b", drivers, cores=2)
    assert a.checksum == b.checksum and a.tables[0].rows == 50_000
    assert a.seed == 42 and a.label == "TeraSort-style data generated by Velocia"

    monkeypatch.chdir(tmp_path)
    cli = CliRunner()
    gen = cli.invoke(app, ["datagen", "--suite", "tera", "--rows", "200000"])
    assert gen.exit_code == 0, gen.output
    (tmp_path / "exp.yaml").write_text(
        "name: tera\nworkload: {kind: job, suite: tera, units: [terasort], rows: 200000}\n"
        "engines: [spark-vanilla, spark-comet]\nreference_engine: spark-vanilla\n"
        "cluster: {runner: local, executors: 1, executor_cores: 2, executor_memory: 2g}\n"
        "measures: [wall_time]\nrepetitions: 2\nmodes: [cold]\n"
    )
    result = cli.invoke(app, ["run", "exp.yaml"])
    assert result.exit_code == 0, result.output
    assert "correctness pass" in result.output
    report_dir = next((tmp_path / "velocia-results" / "reports").iterdir())
    report = json.loads((report_dir / "report.json").read_text())
    rows = {(r["engine"], r["unit_id"]): r for r in report["results"]}
    assert rows[("spark-comet", "terasort")]["correctness"] == "pass"
    assert rows[("spark-comet", "terasort")]["n"] == 2
    assert report["label"] == "Data: TeraSort-style data generated by Velocia."
