"""Sort and WordCount on generated text (T28)."""

import json
import shutil
import subprocess
from pathlib import Path

import pytest
from typer.testing import CliRunner

from velocia.cli.app import app
from velocia.config.models import DataFormat, Suite, WorkloadKind
from velocia.datagen.tera import generate_spark_suite, spark_dataset_id
from velocia.workloads import get_workload

FIXTURE = Path(__file__).parent / "fixtures" / "engines" / "spark-faulty"
FAULTY_IMAGE = "velocia/test-spark-faulty:1"


def test_text_workload() -> None:
    text = get_workload(Suite.text)
    assert text is not None and text.kind is WorkloadKind.job
    assert [u.id for u in text.units()] == ["sort", "wordcount"]
    assert spark_dataset_id(Suite.text, 10, DataFormat.parquet_zstd) == ("text-rows10-parquet-zstd")


@pytest.mark.docker
@pytest.mark.skipif(shutil.which("docker") is None, reason="docker not available")
def test_textgen_sort_wordcount(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    drivers = tmp_path / "drivers"
    fmt = DataFormat.parquet_zstd
    a, _ = generate_spark_suite(Suite.text, 20_000, fmt, tmp_path / "a", drivers, cores=2)
    b, _ = generate_spark_suite(Suite.text, 20_000, fmt, tmp_path / "b", drivers, cores=2)
    assert a.checksum == b.checksum and a.tables[0].name == "text"
    assert a.label == "Text generated by Velocia (Sort, WordCount)"

    build = ["docker", "build", "-q", "-t", FAULTY_IMAGE, str(FIXTURE)]
    subprocess.run(build, check=True, capture_output=True)
    monkeypatch.chdir(tmp_path)
    (tmp_path / "engines").mkdir()
    for fault in ("wrong", "unsorted"):
        (tmp_path / "engines" / f"spark-{fault}.yaml").write_text(
            f"name: spark-{fault}\nimage: {FAULTY_IMAGE}\nspark_versions: ['3.5']\n"
            f"spark_conf: {{spark.velocia.test.fault: {fault}}}\n"
        )
    cli = CliRunner()
    gen = cli.invoke(app, ["datagen", "--suite", "text", "--rows", "100000"])
    assert gen.exit_code == 0, gen.output
    (tmp_path / "exp.yaml").write_text(
        "name: text\nworkload: {kind: job, suite: text, rows: 100000}\n"
        "engines: [spark-vanilla, spark-comet, spark-wrong, spark-unsorted]\n"
        "reference_engine: spark-vanilla\n"
        "cluster: {runner: local, executors: 1, executor_cores: 2, executor_memory: 2g}\n"
        "measures: [wall_time]\nrepetitions: 1\nmodes: [cold]\n"
    )
    result = cli.invoke(app, ["run", "exp.yaml"])
    assert result.exit_code == 0, result.output
    report_dir = next((tmp_path / "velocia-results" / "reports").iterdir())
    report = json.loads((report_dir / "report.json").read_text())
    verdict = {(r["engine"], r["unit_id"]): r["correctness"] for r in report["results"]}
    assert verdict[("spark-vanilla", "sort")] == "pass"
    assert verdict[("spark-vanilla", "wordcount")] == "pass"
    assert verdict[("spark-comet", "sort")] == "pass"
    assert verdict[("spark-comet", "wordcount")] == "pass"
    assert verdict[("spark-unsorted", "sort")] == "fail"
    assert verdict[("spark-wrong", "wordcount")] == "fail"
    checks = [
        json.loads(p.read_text())
        for p in (tmp_path / "velocia-results" / "runs").glob("*-check/checks.json")
    ]
    errors = [u["error"] or "" for c in checks for u in c["units"]]
    assert any("keys out of order" in e for e in errors)
    assert any("counts add up to" in e for e in errors)
