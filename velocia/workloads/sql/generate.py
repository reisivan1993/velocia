"""Regenerate the TPC-H- and TPC-DS-derived query files:
``python -m velocia.workloads.sql.generate``.

The text comes from DuckDB's ``tpch`` and ``tpcds`` extensions (``tpch_queries()`` and
``tpcds_queries()``, default substitution parameters with dates already computed), which is
valid Apache Spark SQL apart from the trailing semicolon and, in TPC-DS, column aliases in
double quotes (an identifier in DuckDB, a string in Spark), which become backticks. Nothing
from the TPC kits is vendored; a test checks the committed files are current.
"""

import re
import sys
from pathlib import Path

import duckdb

from velocia.workloads.sql import QUERIES_DIR

HEADER = (
    "-- {unit_id}: derived from {benchmark} Q{nr}; not an official TPC query or result.\n"
    "-- Generated by velocia.workloads.sql.generate from DuckDB {suite}_queries(); do not edit.\n"
)
QUOTED = re.compile(r'"([^"]*)"')  # DuckDB identifier quotes; Spark wants backticks


def queries(suite: str) -> dict[str, str]:
    """``q<n>.sql`` files for ``tpch`` or ``tpcds``."""
    benchmark = {"tpch": "TPC-H", "tpcds": "TPC-DS"}[suite]
    with duckdb.connect() as con:
        con.execute("SET autoinstall_known_extensions = false")
        con.execute(f"LOAD {suite}")
        rows = con.execute(f"SELECT query_nr, query FROM {suite}_queries() ORDER BY 1").fetchall()
    out = {}
    for nr, query in rows:
        body = "\n".join(line.rstrip() for line in query.strip().splitlines()).removesuffix(";")
        body = QUOTED.sub(r"`\1`", body)
        header = HEADER.format(unit_id=f"q{nr}", benchmark=benchmark, nr=nr, suite=suite)
        out[f"q{nr}.sql"] = header + body + "\n"
    return out


def tpch_queries() -> dict[str, str]:
    return queries("tpch")


def main(root: Path = QUERIES_DIR) -> None:
    for suite in ("tpch", "tpcds"):
        out_dir = root / suite
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in queries(suite).items():
            (out_dir / name).write_text(text, "utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else QUERIES_DIR)
