"""Edge-case workloads on synth data (docs/03-spec.md §1.3).

Units are operators over the generated ``fact`` and ``dim`` tables. The spec's named
workloads are experiments that pair a unit with one swept parameter, for example:

- skewed join: ``join`` sweeping ``zipf_s`` (``key_dist: zipf``), with and without
  ``spark.sql.adaptive.skewJoin.enabled`` as a ``spark_conf`` list
- hot key: ``join`` sweeping ``hot_fraction`` (``key_dist: hotkey``)
- skewed aggregate: ``aggregate`` sweeping ``zipf_s`` or ``keys``
- exploding join: ``exploding_join`` sweeping ``keys`` (fan-out = rows / keys)
- spill: ``sort`` with ``spark.memory.fraction`` as a ``spark_conf`` list
- shuffle partitions: ``aggregate`` with ``spark.sql.shuffle.partitions`` as a list

Examples are in ``examples/synth/``. Each sweep point is its own dataset, named by the hash
of its full spec, so cells at different points never share data by accident.
"""

from dataclasses import dataclass

from velocia.config.models import Suite, SynthSpec, Workload, WorkloadKind
from velocia.datagen.manifest import DatasetManifest
from velocia.workloads import Unit

# Joins use a sort-merge hint: dim is small enough to broadcast, which would hide skew.
SQL = {
    "join": (
        "SELECT /*+ SHUFFLE_MERGE(d) */ d.grp, count(*) AS n, sum(f.p0 % 1000) AS v "
        "FROM fact f JOIN dim d ON f.key = d.key GROUP BY d.grp"
    ),
    "aggregate": (
        "SELECT key, count(*) AS n, sum(p0 % 1000) AS v, max(s) AS m FROM fact GROUP BY key"
    ),
    "exploding_join": (
        "SELECT count(*) AS n, sum(a.p0 % 1000 + b.p0 % 1000) AS v "
        "FROM fact a JOIN fact b ON a.key = b.key"
    ),
    "sort": "SELECT * FROM fact ORDER BY s, id",
}


@dataclass(frozen=True)
class SynthWorkload:
    suite: Suite = Suite.synth
    label: str = "Edge-case data generated by Velocia (synth)"
    kind: WorkloadKind = WorkloadKind.sql

    def units(self, dataset: DatasetManifest | None = None) -> list[Unit]:
        return [Unit(id=name, kind=self.kind, sql=sql) for name, sql in SQL.items()]


SYNTH = SynthWorkload()


def synth_spec(workload: Workload, sweep: dict[str, str]) -> SynthSpec:
    """The generator spec at one sweep point: ``workload.synth`` with the swept values."""
    base = (workload.synth or SynthSpec()).model_dump(mode="json")
    return SynthSpec.model_validate({**base, **sweep})
