"""TPC-H- and TPC-DS-derived data through DuckDB's ``tpch`` and ``tpcds`` extensions (03 §2).

Each table becomes one Parquet file, ``<location>/<table>/part-00000.parquet``, written in the
generator's row order so that runs are reproducible. Generation happens in a temporary
directory next to the target, which is renamed into place only once the manifest is written:
a dataset directory with a manifest is always complete.

The extensions are not bundled with the DuckDB wheel. The first run downloads the one it needs
from DuckDB's extension repository; that is the only network access, and it is announced.
"""

import hashlib
import shutil
import uuid
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import duckdb

from velocia import __version__
from velocia.config.models import DataFormat, Suite
from velocia.datagen.manifest import (
    MANIFEST_FILE,
    DatasetFile,
    DatasetManifest,
    DatasetTable,
    dataset_checksum,
)

ROW_GROUP_SIZE = 1_000_000


@dataclass(frozen=True)
class _Generator:
    extension: str
    procedure: str
    label: str


GENERATORS = {
    Suite.tpch: _Generator("tpch", "dbgen", "derived from TPC-H"),
    Suite.tpcds: _Generator("tpcds", "dsdgen", "derived from TPC-DS"),
}

COMPRESSION = {DataFormat.parquet_snappy: "snappy", DataFormat.parquet_zstd: "zstd"}


class DatagenError(RuntimeError):
    pass


def dataset_id(suite: Suite, scale: float, data_format: DataFormat) -> str:
    return f"{suite.value}-sf{scale:g}-{data_format.value}"


def load_manifest(location: Path) -> DatasetManifest:
    return DatasetManifest.model_validate_json((location / MANIFEST_FILE).read_text("utf-8"))


def generate(
    suite: Suite,
    scale: float,
    data_format: DataFormat,
    out_dir: Path,
    progress: Callable[[str], None] = lambda _: None,
) -> tuple[DatasetManifest, bool]:
    """Generate a dataset under ``out_dir``. Returns the manifest and whether it was created.

    An existing complete dataset with the same ID is reused, not regenerated.
    """
    if suite not in GENERATORS:
        raise DatagenError(f"suite {suite.value!r} is not generated by DuckDB")
    if scale <= 0:
        raise DatagenError("scale factor must be > 0")
    generator = GENERATORS[suite]
    ds_id = dataset_id(suite, scale, data_format)
    location = (out_dir / ds_id).resolve()
    if location.exists():
        if not (location / MANIFEST_FILE).is_file():
            raise DatagenError(f"{location} exists but has no {MANIFEST_FILE}; delete it first")
        return load_manifest(location), False

    out_dir.mkdir(parents=True, exist_ok=True)
    staging = out_dir / f".{ds_id}.tmp-{uuid.uuid4().hex[:8]}"
    staging.mkdir()
    try:
        tables = _generate_tables(generator, scale, data_format, staging, progress)
        manifest = DatasetManifest(
            dataset_id=ds_id,
            suite=suite,
            label=generator.label,
            generator=f"duckdb-{generator.extension}",
            generator_version=duckdb.__version__,
            generator_params={"sf": scale},
            seed=None,  # dbgen and dsdgen are deterministic
            scale=scale,
            data_format=data_format,
            compression=COMPRESSION[data_format],
            row_group_size=ROW_GROUP_SIZE,
            location=str(location),
            tables=tables,
            files=sum(len(t.files) for t in tables),
            bytes=sum(f.bytes for t in tables for f in t.files),
            checksum=dataset_checksum(tables),
            created_at=datetime.now(UTC),
            velocia_version=__version__,
        )
        (staging / MANIFEST_FILE).write_text(manifest.model_dump_json(indent=2) + "\n", "utf-8")
        staging.rename(location)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return manifest, True


def _generate_tables(
    generator: _Generator,
    scale: float,
    data_format: DataFormat,
    staging: Path,
    progress: Callable[[str], None],
) -> list[DatasetTable]:
    # An on-disk database lets DuckDB spill at larger scale factors instead of running out of RAM.
    db_file = staging / "_generate.duckdb"
    try:
        with duckdb.connect(db_file) as con:
            con.execute("SET autoinstall_known_extensions = false")
            _load_extension(con, generator.extension, progress)
            progress(f"Generating data ({generator.label}) at scale factor {scale:g}")
            con.execute(f"CALL {generator.procedure}(sf = ?)", [scale])
            names = [row[0] for row in con.execute("SHOW TABLES").fetchall()]
            return [_write_table(con, name, data_format, staging, progress) for name in names]
    finally:
        db_file.unlink(missing_ok=True)
        db_file.with_suffix(".duckdb.wal").unlink(missing_ok=True)


def _load_extension(
    con: duckdb.DuckDBPyConnection, extension: str, progress: Callable[[str], None]
) -> None:
    try:
        con.execute(f"LOAD {extension}")
    except duckdb.Error:
        progress(f"Downloading the DuckDB {extension} extension (one time, from DuckDB)")
        try:
            con.execute(f"INSTALL {extension}")
            con.execute(f"LOAD {extension}")
        except duckdb.Error as exc:
            raise DatagenError(f"cannot install the DuckDB {extension} extension: {exc}") from exc


def _write_table(
    con: duckdb.DuckDBPyConnection,
    name: str,
    data_format: DataFormat,
    staging: Path,
    progress: Callable[[str], None],
) -> DatasetTable:
    rel = Path(name) / "part-00000.parquet"
    path = staging / rel
    path.parent.mkdir()
    progress(f"Writing {name}")
    # Table names come from the generator; the path may come from --out, so it is quoted.
    quoted_path = str(path).replace("'", "''")
    con.execute(
        f"COPY (SELECT * FROM \"{name}\") TO '{quoted_path}' "
        f"(FORMAT parquet, COMPRESSION {COMPRESSION[data_format]}, ROW_GROUP_SIZE {ROW_GROUP_SIZE})"
    )
    rows, checksum = _content_checksum(con, path)
    return DatasetTable(
        name=name,
        rows=rows,
        checksum=checksum,
        files=[DatasetFile(path=rel.as_posix(), bytes=path.stat().st_size)],
    )


def _content_checksum(con: duckdb.DuckDBPyConnection, path: Path) -> tuple[int, str]:
    """Order-independent hash of the rows as written, read back from the Parquet file.

    Each row is rendered as text with its column names and hashed; the per-row hashes are
    summed, so duplicates count and the result doesn't depend on file layout or compression.
    """
    row = con.execute(
        "SELECT count(*), "
        "coalesce(sum(md5_number_lower(CAST(t AS VARCHAR))), 0), "
        "coalesce(sum(md5_number_upper(CAST(t AS VARCHAR))), 0) "
        "FROM read_parquet(?) t",
        [str(path)],
    ).fetchone()
    assert row is not None
    rows, lower, upper = row
    digest = hashlib.sha256(f"{rows}:{lower}:{upper}".encode()).hexdigest()
    return int(rows), f"sha256:{digest}"
